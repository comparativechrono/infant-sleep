"""Every number quoted in the paper, computed from the result tables.

Usage: python3 -I paper_numbers.py <results_dir> > <results_dir>/paper_numbers.md
Reads results/nyu, results/agenoria and results/robustness (see run_all.sh) and prints Markdown.
Clock times are rounded to the nearest 5 minutes; days of age count the date of birth as day 1.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

R = Path(sys.argv[1])
NYU, AG, ROB = R / "nyu", R / "agenoria", R / "robustness"
summ = pd.read_csv(NYU / "nyu_infant_rhythm_summary.csv")
timing = pd.read_csv(NYU / "nyu_infant_timing_summary.csv")
jumps = pd.read_csv(NYU / "nyu_phase_jumps.csv")
evt = pd.read_csv(NYU / "nyu_emergence_vs_timing.csv")
s24 = np.load(NYU / "nyu_rhythm_windows.npz")["s24"]
el = summ[summ.eligible]
out = []


def h(title):
    out.append(f"\n## {title}\n")


def line(label, value):
    out.append(f"- {label}: {value}")


def q(v, fmt="{:.1f}"):
    v = np.asarray(v, float)
    v = v[~np.isnan(v)]
    p = np.quantile(v, [0.5, 0.25, 0.75])
    return f"median {fmt.format(p[0])} (IQR {fmt.format(p[1])}-{fmt.format(p[2])}; n = {v.size})"


def clock(hours):
    m = int(round(float(hours) * 60 / 5) * 5) % (24 * 60)
    return f"{m // 60:02d}:{m % 60:02d}"


def ordinal(v):
    n = int(round(float(v)))
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


def noon_ref(v):
    v = np.asarray(v, float)
    return np.where(v < 12, v + 24, v)


def qclock(v):
    v = noon_ref(v)
    v = v[~np.isnan(v)]
    p = np.quantile(v, [0.5, 0.25, 0.75])
    return f"median {clock(p[0])} (IQR {clock(p[1])}-{clock(p[2])}; n = {v.size})"


out.append("# Numbers quoted in the paper\n\nGenerated by analysis/paper_numbers.py from the tables in results/.")

h("Cohort and logging")
line("Infants in the NYU file", len(summ))
line("Days logged per infant", q(summ.days_logged, "{:.0f}"))
line("Total infant-days logged", int(summ.days_logged.sum()))
line("Age at first logged day (day 1 = date of birth)", q(summ.first_logged_day, "{:.0f}"))
line("Infants first logged by day 7 / by day 21",
     f"{int((summ.first_logged_day <= 7).sum())} / {int((summ.first_logged_day <= 21).sum())}")
line("Age at last logged day", q(summ.last_logged_day, "{:.0f}"))
has_win = summ.first_window_day.notna()
line("Infants with at least one usable 14-day window", int(has_win.sum()))
line("First usable window centred on or before day 21", int((summ.first_window_day <= 21).sum()))
line("First usable window centred on or before day 56", int((summ.first_window_day <= 56).sum()))
line("Plateau measurable (>= 28 windows in days 120-240)", int(summ.plateau_s24.notna().sum()))
line("Plateau >= 0.10", int((summ.plateau_s24 >= 0.10).sum()))
line("Eligible for emergence ages (first window <= day 21 and plateau >= 0.10)", int(summ.eligible.sum()))
line("Days logged per eligible infant", q(el.days_logged, "{:.0f}"))

h("Strength of the 24-h rhythm")
line("Plateau (median share of variance at 24 h, days 120-240), eligible infants", q(el.plateau_s24, "{:.3f}"))
for wk in (2, 4, 8, 12, 26, 52):
    line(f"24-h share of variance at week {wk}, eligible infants", q(el[f"s24_week{wk}"], "{:.3f}"))
for label, rows in (("all infants", slice(None)), ("eligible infants", el.infant.to_numpy() - 1)):
    with np.errstate(all="ignore"):
        med = np.nanmedian(s24[rows], axis=0)
    level = med[181]
    half_day = int(np.flatnonzero(med >= level / 2)[0]) + 1
    line(f"Population median at day 182 ({label})", f"{level:.3f}; first reaches half of it on day {half_day}")

h("Early 24-h rhythm (first usable window)")
spec = pd.read_csv(ROB / "first_window_specificity.csv")
line("Centre of first usable window, eligible infants", q(spec.first_window_day, "{:.0f}"))
line("24-h share of variance in first window", q(spec.s24, "{:.3f}"))
line("Power at 24 h / median power at 20-22 h and 26-28 h", q(spec.flank_ratio, "{:.1f}"))
line("Share of infants with ratio > 2", f"{np.mean(spec.flank_ratio > 2):.1%}")
line("Share whose strongest 20-28 h peak is within 0.5 h of 24 h", f"{np.mean(np.abs(spec.circ_peak_h - 24) <= 0.5 + 1e-9):.1%}")
surr = pd.read_csv(ROB / "surrogate_24h.csv")
for w, g in surr.groupby("window", sort=False):
    line(f"Surrogate test, {w} window: share with p < 0.05",
         f"{np.mean(g.p < 0.05):.1%} of {len(g)} infants (median 24-h share {g.s24.median():.3f} vs surrogate {g.surrogate_median.median():.3f})")

h("Age at half-plateau (t50) and absolute threshold (t_abs)")
t = el.t50_day.dropna()
line("t50 (days)", q(t, "{:.2f}"))
line("t50 in weeks", f"median {t.median() / 7:.1f}; IQR {t.quantile(.25) / 7:.1f}-{t.quantile(.75) / 7:.1f}")
line("t50 10th-90th percentile (days)", f"{t.quantile(.1):.0f}-{t.quantile(.9):.0f} "
     f"({t.quantile(.1) / 7:.1f}-{t.quantile(.9) / 7:.1f} weeks); range {t.min():.0f}-{t.max():.0f}")
line("t50 censoring", el.t50_censoring.fillna("").replace("", "missing").value_counts().to_dict())
line("Share reaching half-plateau by 8 / 12 / 16 weeks",
     f"{np.mean(t <= 56):.1%} / {np.mean(t <= 84):.1%} / {np.mean(t <= 112):.1%}")
ta = el.t_abs_day.dropna()
line("t_abs (24-h share >= 0.20), days", q(ta, "{:.0f}"))
line("t_abs censoring", el.t_abs_censoring.fillna("").replace("", "missing").value_counts().to_dict())
line("Spearman t50 vs plateau", f"{stats.spearmanr(el.t50_day, el.plateau_s24, nan_policy='omit')[0]:.2f}")

h("Free-running screen")
line("Infants flagged with a sustained non-24-h rhythm", int(summ.fr_episode.sum()))
notes = summ[summ.note.notna()]
for _, r in notes.iterrows():
    line(f"Note, infant {r.infant}", r.note)
power = pd.read_csv(ROB / "free_running_power.csv")
N = int((summ.first_window_day <= 56).sum())
for _, r in power.iterrows():
    if r.duration_days == 0:
        line("False positives in unmodified first 140 days", f"{int(r.n_detected)} of {int(r.n_infants)}")
        continue
    bound = (f"95% upper bound on prevalence given 0 of {N}: {(1 - 0.05 ** (1 / N)) / r.sensitivity:.1%}"
             if r.sensitivity > 0 else "not detectable by design (the screen needs a peak >= 0.75 h from 24 h)")
    line(f"Injected tau {r.tau_h} h for {int(r.duration_days)} days",
         f"detected in {r.sensitivity:.0%} of {int(r.n_infants)} (median period {r.median_detected_period_h}); {bound}")

h("Sleep timing")
windows = {"6mo": "6 months (days 152-213)", "12mo": "12 months (days 335-396)",
           "18mo": "18 months (days 517-578)", "24mo": "24 months (days 669-730)"}
for k, lab in windows.items():
    line(f"{lab}: bedtime", qclock(timing[f"bedtime_{k}"]))
    line(f"{lab}: wake time", qclock(timing[f"wake_time_{k}"]))
    line(f"{lab}: mid-sleep", qclock(timing[f"mid_sleep_{k}"]))
    line(f"{lab}: night length (h)", q(timing[f"night_period_{k}"], "{:.2f}"))
for a, b in (("6mo", "12mo"), ("12mo", "18mo"), ("18mo", "24mo"), ("6mo", "24mo")):
    x, y = noon_ref(timing[f"mid_sleep_{a}"]), noon_ref(timing[f"mid_sleep_{b}"])
    m = ~np.isnan(x) & ~np.isnan(y)
    line(f"Mid-sleep stability {a} -> {b}", f"Spearman rho {stats.spearmanr(x[m], y[m])[0]:.2f} (n = {m.sum()})")
line("Phase jumps flagged", f"{len(jumps)} episodes in {jumps.infant.nunique()} infants; "
     f"|shift| median {jumps.shift_h.abs().median():.1f} h (range {jumps.shift_h.abs().min():.1f}-"
     f"{jumps.shift_h.abs().max():.1f}); span median {jumps.span_days.median():.0f} days")

h("Emergence age and later sleep timing")
prim = evt[(evt.predictor == evt.predictor.iloc[0]) & (evt.age == "12mo")]
line("Tests in the table", len(evt))
for _, r in prim.iterrows():
    line(f"Primary, {r.outcome} at 12 months",
         f"n = {r.n}, rho = {r.spearman_rho:.3f}, p = {r.p:.3g}, Holm p = {r.p_holm_primary:.3g}, "
         f"Theil-Sen {r.theil_sen_min_per_10_days:.1f} min per 10 days (95% CI {r.ci95_low:.1f} to {r.ci95_high:.1f}), "
         f"partial rho given plateau {r.partial_rho_given_plateau:.3f}")
sec = evt.drop(prim.index)
line("Secondary tests with unadjusted p < 0.05",
     "; ".join(f"{r.predictor} vs {r.outcome} at {r.age}: rho {r.spearman_rho:.3f}, p {r.p:.3g}, n {r.n}"
               for _, r in sec[sec.p < 0.05].iterrows()) or "none")
line("Largest |rho| among secondary tests", f"{sec.spearman_rho.abs().max():.3f}")

h("Robustness of the half-plateau age")
sens = pd.read_csv(ROB / "definition_sensitivity.csv")
for _, r in sens.iterrows():
    line(f"Plateau days {r.plateau_days}, threshold {r.threshold:.0%}",
         f"median {r['median']:.1f} days (IQR {r.q1:.1f}-{r.q3:.1f}); {int(r.n_reached)} of {int(r.n_eligible)} reached it")
wl = pd.read_csv(ROB / "window_length_t50.csv")
ok = wl[["t50_14d", "t50_10d"]].notna().all(axis=1)
line("10-day windows: t50", q(wl.t50_10d, "{:.1f}"))
line("10-day vs 14-day t50", f"Spearman rho {stats.spearmanr(wl.t50_14d[ok], wl.t50_10d[ok])[0]:.2f}; "
     f"median paired difference {np.median(wl.t50_10d[ok] - wl.t50_14d[ok]):.1f} days (n = {ok.sum()})")

h("External check: Agenoria infants")
ag = pd.read_csv(AG / "agenoria_emergence_summary.csv")
for _, r in ag.iterrows():
    line(r.infant, f"days logged {r.days_logged_first_year}; first window day {r.first_window_day}; "
         f"plateau {r.plateau_s24:.3f} ({ordinal(r.plateau_nyu_percentile)} NYU percentile); "
         f"t50 day {r.t50_day:.0f} ({ordinal(r.t50_nyu_percentile)}); t_abs day {r.t_abs_day:.0f} "
         f"({ordinal(r.t_abs_nyu_percentile)}); first-window flank ratio {r.first_window_flank_ratio:.2f}; "
         f"24-h share at week 52 {r.s24_week52:.3f}; free-running {r.fr_episode}; "
         f"windows with 20-28 h peak within 0.5 h of 24 h {r['windows_peak_within_0.5h_of_24']:.1%}")

print("\n".join(out))
